"""Traces -> training data for an open model. Checks are the reward: to score a new completion for a reading, the
checks that looked at that reading are run again with the new completion in its place.

  sft.jsonl   readings whose checks all passed (rejection-sampling fine-tune)
  grpo.jsonl  every reading with at least one re-runnable check (GRPO, rewards from the checks)
"""
import json
from pathlib import Path

from . import trace as traces
from .core import CHECKS, ReadRequest, Source
from .models import messages_for
from .schema import from_jsonable, load_schema, parse


def _request(r, sources):
    q = dict(r["request"])
    q["sources"] = [Source(**sources[s]) if s in sources else Source(s) for s in q["sources"]]
    return ReadRequest(**q)


def _replayable(c):
    return all("opaque" not in a for a in [*c["args"], *c["kwargs"].values()]) and c["fn"] in CHECKS


def build(patterns, agent=None, min_reward=1.0):
    """Returns (sft_rows, grpo_rows, stats). The .shio program must be loaded first so its checks can be re-run."""
    runs = list(traces.load(patterns))
    if agent:
        runs = [r for r in runs if r["agent"] == agent or r["agent"].endswith("." + agent)]
    values = {x["id"]: (x["schema"], x["value"]) for r in runs for x in r["readings"]}
    sft, grpo = [], []
    stats = {"runs": len(runs), "readings": 0, "with_checks": 0, "sft": 0, "grpo": 0, "not_replayable": 0}
    by_reading = {}
    for r in runs:   # a check in any run (a nested agent, say) may look at a reading
        for c in r["checks"]:
            if not c.get("reward", True):    # a `when` steers control flow; it says nothing about quality
                continue
            for i in dict.fromkeys(c["readings"]):
                by_reading.setdefault(i, []).append(c)
    for run in runs:
        for x in run["readings"]:
            stats["readings"] += 1
            mine = by_reading.get(x["id"], [])
            if not mine:
                continue
            stats["with_checks"] += 1
            prompt = messages_for(_request(x, run["sources"]))
            reward = sum(c["passed"] for c in mine) / len(mine)
            if not x["error"] and reward >= min_reward:
                sft.append({"messages": prompt + [{"role": "assistant", "content": x["raw"]}], "reward": reward})
            ok = [c for c in mine if _replayable(c)]
            stats["not_replayable"] += len(mine) - len(ok)
            if ok:
                refs = {a["reading"] for c in ok for a in [*c["args"], *c["kwargs"].values()] if "reading" in a}
                grpo.append({"prompt": prompt, "shio": json.dumps({
                    "reading": x["id"], "schema": x["schema"],
                    "checks": [{k: c[k] for k in ("name", "fn", "args", "kwargs")} for c in ok],
                    "values": {i: values[i] for i in refs if i in values and i != x["id"]}})})
    stats["sft"], stats["grpo"] = len(sft), len(grpo)
    return sft, grpo, stats


def score(spec, completion):
    """Mean of the reading's checks re-run with `completion` as the reading. Unparseable -> 0."""
    spec = json.loads(spec) if isinstance(spec, str) else spec
    schema = load_schema(spec["schema"])
    value, err = parse(schema, completion)
    if err:
        return 0.0

    def arg(a):
        if "reading" in a:
            if a["reading"] == spec["reading"]:
                return value
            ref, data = spec["values"][a["reading"]]
            return from_jsonable(load_schema(ref), data)
        return a["const"]
    total = 0.0
    for c in spec["checks"]:
        try:
            out = CHECKS[c["fn"]](*[arg(a) for a in c["args"]], **{k: arg(v) for k, v in c["kwargs"].items()})
            total += bool(out[0] if isinstance(out, tuple) else out)
        except Exception:
            pass
    return total / len(spec["checks"])


def reward(prompts, completions, shio, **kwargs):
    """TRL GRPOTrainer reward function (the dataset's `shio` column arrives as a keyword argument)."""
    texts = [c[-1]["content"] if isinstance(c, list) else c for c in completions]
    return [score(s, t) for s, t in zip(shio, texts)]


GRPO_SCRIPT = '''"""Generated by `shio train`. Needs a GPU and: pip install trl datasets peft"""
import shio
from datasets import load_dataset
from trl import GRPOConfig, GRPOTrainer

shio.load({src!r})                     # registers the program's checks, which are the reward
ds = load_dataset("json", data_files={data!r}, split="train")
args = GRPOConfig(output_dir={out!r}, num_generations=4, per_device_train_batch_size=4, max_completion_length=1024,
                  learning_rate=1e-6, logging_steps=1)
trainer = GRPOTrainer(model={model!r}, reward_funcs=shio.train.reward, args=args, train_dataset=ds)
trainer.train()
trainer.save_model({out!r})
'''

SFT_SCRIPT = '''"""Generated by `shio train`. Needs a GPU and: pip install trl datasets peft"""
from datasets import load_dataset
from trl import SFTConfig, SFTTrainer

ds = load_dataset("json", data_files={data!r}, split="train").remove_columns(["reward"])
trainer = SFTTrainer(model={model!r}, train_dataset=ds, args=SFTConfig(output_dir={out!r}, logging_steps=1))
trainer.train()
trainer.save_model({out!r})
'''


def write(src, patterns, model, out, agent=None, method="grpo", min_reward=1.0):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    sft, grpo, stats = build(patterns, agent, min_reward)
    for name, rows in (("sft.jsonl", sft), ("grpo.jsonl", grpo)):
        (out / name).write_text("".join(json.dumps(r) + "\n" for r in rows))
    ckpt = str(out / "checkpoint")
    (out / "train_grpo.py").write_text(GRPO_SCRIPT.format(src=str(Path(src).resolve()), data=str(out / "grpo.jsonl"),
                                                          model=model, out=ckpt))
    (out / "train_sft.py").write_text(SFT_SCRIPT.format(data=str(out / "sft.jsonl"), model=model, out=ckpt))
    stats["script"] = str(out / f"train_{method}.py")
    return stats
